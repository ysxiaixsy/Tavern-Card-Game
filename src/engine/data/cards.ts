/** All leader variants of a faction, in data order (drives the UI picker). */
export function leadersOf(faction: CardDef['faction']): CardDef[] {
  return CARD_DEFS.filter((def) => def.type === 'leader' && def.faction === faction);
}

const CARD_INDEX: Record<string, CardDef> = {};
for (const def of CARD_DEFS) {
  if (CARD_INDEX[def.id]) {
    throw new Error(`Duplicate card def id: ${def.id}`);
  }
  CARD_INDEX[def.id] = def;
}

export function getCardDef(defId: string): CardDef {
  const def = CARD_INDEX[defId];
  if (!def) {
    throw new Error(`Unknown card def id: ${defId}`);
  }
  return def;
}

export function hasCardDef(defId: string): boolean {
  return defId in CARD_INDEX;
}
